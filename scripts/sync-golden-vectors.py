def load_fixture(name: str) -> dict:
    path = FIXTURES / name
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def main() -> int:
    slh = load_fixture("slh_dsa_sha2_golden_vectors.json")
    ml = load_fixture("ml_dsa_44_golden.json")
    secp = load_fixture("secp256k1_bip340_row0.json")

    write_rust_vectors(slh, ml, secp)
    write_python_vectors(slh, ml, secp)
    write_js_vectors(slh, ml, secp, ROOT / "tests" / "vectors" / "nodejs", dts=True)
    write_js_vectors(slh, ml, secp, ROOT / "tests" / "vectors" / "wasm", dts=False)
    write_c_headers(slh, ml, secp)

    print("Golden vectors synced from tests/vectors/fixtures/")
    return 0


if __name__ == "__main__":
    sys.exit(main())